        REFERENCES clinica.medicamento (id_medicamento)
        ON DELETE RESTRICT,
    CONSTRAINT ck_reclinea_numero   CHECK (numero_linea > 0),
    CONSTRAINT ck_reclinea_cantidad CHECK (cantidad > 0)
);

CREATE TABLE clinica.dispensacion (
