-- =====================================================================
--  Clínica Vida Plena — Esquema (PostgreSQL)
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS clinica;


-- Necesaria para las restricciones EXCLUDE
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA clinica;

-- ---------------------------------------------------------------------
--  Tablas base
-- ---------------------------------------------------------------------

CREATE TABLE clinica.sede (
    id_sede     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100) NOT NULL,
    direccion   VARCHAR(200) NOT NULL,
    telefono    VARCHAR(20)  NOT NULL,

    CONSTRAINT pk_sede PRIMARY KEY (id_sede),
    CONSTRAINT uq_sede_nombre UNIQUE (nombre)
);

CREATE TABLE clinica.persona (
    id_persona        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    documento         VARCHAR(20)  NOT NULL,
    nombres           VARCHAR(80)  NOT NULL,
    apellido_paterno  VARCHAR(60)  NOT NULL,
    apellido_materno  VARCHAR(60)  NULL,
    fecha_nacimiento  DATE         NOT NULL,
    sexo              CHAR(1)      NOT NULL,
    telefono          VARCHAR(20)  NULL,
    email             VARCHAR(120) NULL,
    direccion         VARCHAR(200) NULL,

    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_documento UNIQUE (documento),
    CONSTRAINT uq_persona_email UNIQUE (email),
    CONSTRAINT ck_persona_fecha_nacimiento
        CHECK (fecha_nacimiento >= DATE '1900-01-01' AND fecha_nacimiento <= CURRENT_DATE),
    CONSTRAINT ck_persona_sexo CHECK (sexo IN ('F','M','X')),
    CONSTRAINT ck_persona_email CHECK (email IS NULL OR email LIKE '_%@_%._%')
);

CREATE TABLE clinica.aseguradora (
    id_aseguradora  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(100) NOT NULL,
    telefono        VARCHAR(20)  NULL,

    CONSTRAINT pk_aseguradora PRIMARY KEY (id_aseguradora),
    CONSTRAINT uq_aseguradora_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
--  Paciente (subtipo de persona)
-- ---------------------------------------------------------------------

CREATE TABLE clinica.paciente (
    id_persona            INTEGER      NOT NULL,
    id_responsable        INTEGER      NULL,
    id_aseguradora        INTEGER      NULL,
    numero_poliza         VARCHAR(30)  NULL,
    porcentaje_cobertura  NUMERIC(5,2) NULL,
    fecha_registro        DATE         NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_paciente PRIMARY KEY (id_persona),

    -- Subtipo de persona: si se borra la persona, se borra su rol de paciente
    CONSTRAINT fk_paciente_persona FOREIGN KEY (id_persona)
        REFERENCES clinica.persona (id_persona)
        ON DELETE CASCADE ON UPDATE CASCADE,

    -- No se puede borrar un paciente que es responsable de otro
    CONSTRAINT fk_paciente_responsable FOREIGN KEY (id_responsable)
        REFERENCES clinica.paciente (id_persona)
        ON DELETE RESTRICT,

    -- No se borra una aseguradora con pacientes afiliados
    CONSTRAINT fk_paciente_aseguradora FOREIGN KEY (id_aseguradora)
        REFERENCES clinica.aseguradora (id_aseguradora)
        ON DELETE RESTRICT,

    CONSTRAINT ck_paciente_no_autoresponsable
        CHECK (id_responsable <> id_persona),

    CONSTRAINT ck_paciente_cobertura_rango
        CHECK (porcentaje_cobertura BETWEEN 0 AND 100),

    -- Cobertura y aseguradora van juntas: o las dos o ninguna
    CONSTRAINT ck_paciente_seguro_completo
        CHECK ((id_aseguradora IS NULL) = (porcentaje_cobertura IS NULL)),

    -- Sin aseguradora no puede haber número de póliza
    CONSTRAINT ck_paciente_poliza
        CHECK (id_aseguradora IS NOT NULL OR numero_poliza IS NULL)
);

-- ---------------------------------------------------------------------
--  Empleados (subtipo de persona).
-- ---------------------------------------------------------------------

CREATE TABLE clinica.empleado (
    id_persona          INTEGER     NOT NULL,
    numero_empleado     VARCHAR(20) NOT NULL,
    tipo_empleado       VARCHAR(15) NOT NULL,
    fecha_contratacion  DATE        NOT NULL DEFAULT CURRENT_DATE,
    activo              BOOLEAN     NOT NULL DEFAULT true,

    CONSTRAINT pk_empleado PRIMARY KEY (id_persona),
    CONSTRAINT uq_empleado_numero UNIQUE (numero_empleado),
    CONSTRAINT uq_empleado_tipo UNIQUE (id_persona, tipo_empleado),
    CONSTRAINT fk_empleado_persona FOREIGN KEY (id_persona)
        REFERENCES clinica.persona (id_persona)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_empleado_tipo
        CHECK (tipo_empleado IN ('medico','recepcionista','farmaceutico')),
    CONSTRAINT ck_empleado_fecha_contratacion
        CHECK (fecha_contratacion <= CURRENT_DATE)
);

CREATE TABLE clinica.medico (
    id_persona          INTEGER     NOT NULL,
    tipo_empleado       VARCHAR(15) NOT NULL DEFAULT 'medico',
    cedula_profesional  VARCHAR(30) NOT NULL,

    CONSTRAINT pk_medico PRIMARY KEY (id_persona),
    CONSTRAINT uq_medico_cedula UNIQUE (cedula_profesional),
    CONSTRAINT ck_medico_tipo CHECK (tipo_empleado = 'medico'),
    CONSTRAINT fk_medico_empleado FOREIGN KEY (id_persona, tipo_empleado)
        REFERENCES clinica.empleado (id_persona, tipo_empleado)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE clinica.recepcionista (
    id_persona     INTEGER     NOT NULL,
    tipo_empleado  VARCHAR(15) NOT NULL DEFAULT 'recepcionista',
    id_sede        INTEGER     NOT NULL,

    CONSTRAINT pk_recepcionista PRIMARY KEY (id_persona),
    CONSTRAINT ck_recepcionista_tipo CHECK (tipo_empleado = 'recepcionista'),
    CONSTRAINT fk_recepcionista_empleado FOREIGN KEY (id_persona, tipo_empleado)
        REFERENCES clinica.empleado (id_persona, tipo_empleado)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_recepcionista_sede FOREIGN KEY (id_sede)
        REFERENCES clinica.sede (id_sede)
        ON DELETE RESTRICT
);

CREATE TABLE clinica.farmaceutico (
    id_persona          INTEGER     NOT NULL,
    tipo_empleado       VARCHAR(15) NOT NULL DEFAULT 'farmaceutico',
    id_sede             INTEGER     NOT NULL,
    licencia_sanitaria  VARCHAR(30) NOT NULL,

    CONSTRAINT pk_farmaceutico PRIMARY KEY (id_persona),
    CONSTRAINT uq_farmaceutico_licencia UNIQUE (licencia_sanitaria),
    CONSTRAINT ck_farmaceutico_tipo CHECK (tipo_empleado = 'farmaceutico'),
    CONSTRAINT fk_farmaceutico_empleado FOREIGN KEY (id_persona, tipo_empleado)
        REFERENCES clinica.empleado (id_persona, tipo_empleado)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_farmaceutico_sede FOREIGN KEY (id_sede)
        REFERENCES clinica.sede (id_sede)
        ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
--  Especialidades y horarios
-- ---------------------------------------------------------------------

CREATE TABLE clinica.especialidad (
    id_especialidad  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(80)   NOT NULL,
    precio_consulta  NUMERIC(10,2) NOT NULL,

    CONSTRAINT pk_especialidad PRIMARY KEY (id_especialidad),
    CONSTRAINT uq_especialidad_nombre UNIQUE (nombre),
    CONSTRAINT ck_especialidad_precio CHECK (precio_consulta > 0)
);

CREATE TABLE clinica.medico_especialidad (
    id_medico        INTEGER NOT NULL,
    id_especialidad  INTEGER NOT NULL,

    CONSTRAINT pk_medico_especialidad PRIMARY KEY (id_medico, id_especialidad),
    CONSTRAINT fk_medesp_medico FOREIGN KEY (id_medico)
        REFERENCES clinica.medico (id_persona)
        ON DELETE CASCADE,
    CONSTRAINT fk_medesp_especialidad FOREIGN KEY (id_especialidad)
        REFERENCES clinica.especialidad (id_especialidad)
        ON DELETE RESTRICT
);

CREATE TABLE clinica.horario (
    id_horario   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_medico    INTEGER  NOT NULL,
    id_sede      INTEGER  NOT NULL,
    dia_semana   SMALLINT NOT NULL,
    hora_inicio  TIME     NOT NULL,
    hora_fin     TIME     NOT NULL,

    CONSTRAINT pk_horario PRIMARY KEY (id_horario),
    CONSTRAINT fk_horario_medico FOREIGN KEY (id_medico)
        REFERENCES clinica.medico (id_persona)
        ON DELETE CASCADE,
    CONSTRAINT fk_horario_sede FOREIGN KEY (id_sede)
        REFERENCES clinica.sede (id_sede)
        ON DELETE RESTRICT,
    CONSTRAINT ck_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_rango CHECK (hora_fin > hora_inicio),
    -- Un médico no puede tener dos bloques encimados el mismo día
    CONSTRAINT ex_horario_sin_solape EXCLUDE USING gist (
        id_medico WITH =,
        dia_semana WITH =,
        tsrange(DATE '2000-01-01' + hora_inicio, DATE '2000-01-01' + hora_fin) WITH &&
    )
);

-- ---------------------------------------------------------------------
--  Citas y consultas
-- ---------------------------------------------------------------------

CREATE TABLE clinica.cita (
    id_cita          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_paciente      INTEGER        NOT NULL,
    id_medico        INTEGER        NOT NULL,
    id_especialidad  INTEGER        NOT NULL,
    id_sede          INTEGER        NOT NULL,
    fecha_hora       TIMESTAMPTZ(0) NOT NULL,
    estado           VARCHAR(12)    NOT NULL DEFAULT 'programada',
    creada_en        TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_cita PRIMARY KEY (id_cita),
    CONSTRAINT fk_cita_paciente FOREIGN KEY (id_paciente)
        REFERENCES clinica.paciente (id_persona)
        ON DELETE RESTRICT,
    CONSTRAINT fk_cita_medico_especialidad FOREIGN KEY (id_medico, id_especialidad)
        REFERENCES clinica.medico_especialidad (id_medico, id_especialidad)
        ON DELETE RESTRICT,
    CONSTRAINT fk_cita_sede FOREIGN KEY (id_sede)
        REFERENCES clinica.sede (id_sede)
        ON DELETE RESTRICT,
    CONSTRAINT ck_cita_bloque_30
        CHECK (EXTRACT(MINUTE FROM fecha_hora) IN (0,30) AND EXTRACT(SECOND FROM fecha_hora) = 0),
    CONSTRAINT ck_cita_estado
        CHECK (estado IN ('programada','confirmada','cancelada','atendida','no_asistio'))
);

-- Un médico no puede tener dos citas activas a la misma hora
CREATE UNIQUE INDEX uq_cita_medico_hora
    ON clinica.cita (id_medico, fecha_hora)
    WHERE estado <> 'cancelada';

-- Un paciente no puede tener dos citas activas a la misma hora
CREATE UNIQUE INDEX uq_cita_paciente_hora
    ON clinica.cita (id_paciente, fecha_hora)
    WHERE estado <> 'cancelada';

CREATE TABLE clinica.consulta (
    id_consulta          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cita              INTEGER      NOT NULL,
    motivo               VARCHAR(300) NOT NULL,
    presion_sistolica    SMALLINT     NULL,
    presion_diastolica   SMALLINT     NULL,
    frecuencia_cardiaca  SMALLINT     NULL,
    temperatura_c        NUMERIC(4,1) NULL,
    peso_kg              NUMERIC(5,2) NULL,
    talla_cm             NUMERIC(5,1) NULL,
    notas_clinicas       TEXT         NULL,
    registrada_en        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_consulta PRIMARY KEY (id_consulta),
    CONSTRAINT uq_consulta_cita UNIQUE (id_cita),
    CONSTRAINT fk_consulta_cita FOREIGN KEY (id_cita)
        REFERENCES clinica.cita (id_cita)
        ON DELETE RESTRICT,
    CONSTRAINT ck_consulta_sistolica    CHECK (presion_sistolica   BETWEEN 50 AND 260),
    CONSTRAINT ck_consulta_diastolica   CHECK (presion_diastolica  BETWEEN 30 AND 160),
    CONSTRAINT ck_consulta_presion      CHECK (presion_sistolica > presion_diastolica),
    CONSTRAINT ck_consulta_frecuencia   CHECK (frecuencia_cardiaca BETWEEN 20 AND 250),
    CONSTRAINT ck_consulta_temperatura  CHECK (temperatura_c       BETWEEN 30 AND 45),
    CONSTRAINT ck_consulta_peso         CHECK (peso_kg  > 0 AND peso_kg  <= 500),
    CONSTRAINT ck_consulta_talla        CHECK (talla_cm > 0 AND talla_cm <= 260)
);

CREATE TABLE clinica.diagnostico (
    id_diagnostico  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo_cie10    VARCHAR(10)  NOT NULL,
    descripcion     VARCHAR(200) NOT NULL,

    CONSTRAINT pk_diagnostico PRIMARY KEY (id_diagnostico),
    CONSTRAINT uq_diagnostico_cie10 UNIQUE (codigo_cie10)
);

CREATE TABLE clinica.consulta_diagnostico (
    id_consulta     INTEGER      NOT NULL,
    id_diagnostico  INTEGER      NOT NULL,
    es_principal    BOOLEAN      NOT NULL DEFAULT false,
    observaciones   VARCHAR(300) NULL,

    CONSTRAINT pk_consulta_diagnostico PRIMARY KEY (id_consulta, id_diagnostico),
    CONSTRAINT fk_condiag_consulta FOREIGN KEY (id_consulta)
        REFERENCES clinica.consulta (id_consulta)
        ON DELETE CASCADE,
    CONSTRAINT fk_condiag_diagnostico FOREIGN KEY (id_diagnostico)
        REFERENCES clinica.diagnostico (id_diagnostico)
        ON DELETE RESTRICT
);

-- Solo un diagnóstico principal por consulta
CREATE UNIQUE INDEX uq_consulta_diagnostico_principal
    ON clinica.consulta_diagnostico (id_consulta)
    WHERE es_principal;

-- ---------------------------------------------------------------------
--  Farmacia: medicamentos, lotes, existencias, recetas y dispensación
-- ---------------------------------------------------------------------

CREATE TABLE clinica.medicamento (
    id_medicamento  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(120)  NOT NULL,
    presentacion    VARCHAR(60)   NOT NULL,
    concentracion   VARCHAR(40)   NOT NULL,
    precio_venta    NUMERIC(10,2) NOT NULL,
    activo          BOOLEAN       NOT NULL DEFAULT true,

    CONSTRAINT pk_medicamento PRIMARY KEY (id_medicamento),
    CONSTRAINT uq_medicamento UNIQUE (nombre, presentacion, concentracion),
    CONSTRAINT ck_medicamento_precio CHECK (precio_venta >= 0)
);

CREATE TABLE clinica.lote (
    id_lote            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_medicamento     INTEGER     NOT NULL,
    numero_lote        VARCHAR(30) NOT NULL,
    fecha_vencimiento  DATE        NOT NULL,

    CONSTRAINT pk_lote PRIMARY KEY (id_lote),
    CONSTRAINT uq_lote_medicamento_numero UNIQUE (id_medicamento, numero_lote),
    CONSTRAINT fk_lote_medicamento FOREIGN KEY (id_medicamento)
        REFERENCES clinica.medicamento (id_medicamento)
        ON DELETE RESTRICT
);

CREATE TABLE clinica.existencia (
    id_lote        INTEGER NOT NULL,
    id_sede        INTEGER NOT NULL,
    stock          INTEGER NOT NULL DEFAULT 0,
    fecha_ingreso  DATE    NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_existencia PRIMARY KEY (id_lote, id_sede),
    CONSTRAINT fk_existencia_lote FOREIGN KEY (id_lote)
        REFERENCES clinica.lote (id_lote)
        ON DELETE RESTRICT,
    CONSTRAINT fk_existencia_sede FOREIGN KEY (id_sede)
        REFERENCES clinica.sede (id_sede)
        ON DELETE RESTRICT,
    CONSTRAINT ck_existencia_stock CHECK (stock >= 0)
);

CREATE TABLE clinica.receta (
    id_receta      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_consulta    INTEGER     NOT NULL,
    fecha_emision  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado         VARCHAR(12) NOT NULL DEFAULT 'pendiente',
    indicaciones   TEXT        NULL,

    CONSTRAINT pk_receta PRIMARY KEY (id_receta),
    CONSTRAINT uq_receta_consulta UNIQUE (id_consulta),
    CONSTRAINT fk_receta_consulta FOREIGN KEY (id_consulta)
        REFERENCES clinica.consulta (id_consulta)
        ON DELETE RESTRICT,
    CONSTRAINT ck_receta_estado CHECK (estado IN ('pendiente','dispensada','anulada'))
);

CREATE TABLE clinica.receta_linea (
    id_receta       INTEGER     NOT NULL,
