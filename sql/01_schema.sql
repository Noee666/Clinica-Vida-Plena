-- ---------------------------------------------------------------------
--  Facturación y pagos
-- ---------------------------------------------------------------------

CREATE TABLE clinica.factura (
    id_factura            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_consulta           INTEGER       NOT NULL,
    id_aseguradora        INTEGER       NULL,
    fecha_emision         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    subtotal              NUMERIC(12,2) NOT NULL DEFAULT 0,
    porcentaje_cobertura  NUMERIC(5,2)  NOT NULL DEFAULT 0,
    monto_seguro          NUMERIC(12,2) NOT NULL DEFAULT 0,
    monto_paciente        NUMERIC(12,2) NOT NULL DEFAULT 0,
    saldo                 NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado                VARCHAR(10)   NOT NULL DEFAULT 'pendiente',

    CONSTRAINT pk_factura PRIMARY KEY (id_factura),
    CONSTRAINT uq_factura_consulta UNIQUE (id_consulta),
    CONSTRAINT fk_factura_consulta FOREIGN KEY (id_consulta)
        REFERENCES clinica.consulta (id_consulta)
        ON DELETE RESTRICT,
    CONSTRAINT fk_factura_aseguradora FOREIGN KEY (id_aseguradora)
        REFERENCES clinica.aseguradora (id_aseguradora)
        ON DELETE RESTRICT,
    CONSTRAINT ck_factura_subtotal        CHECK (subtotal >= 0),
    CONSTRAINT ck_factura_cobertura_rango CHECK (porcentaje_cobertura BETWEEN 0 AND 100),
    -- Sin aseguradora no hay cobertura
    CONSTRAINT ck_factura_cobertura_sin_seguro
        CHECK (id_aseguradora IS NOT NULL OR porcentaje_cobertura = 0),
    CONSTRAINT ck_factura_monto_seguro    CHECK (monto_seguro >= 0),
    CONSTRAINT ck_factura_monto_paciente  CHECK (monto_paciente >= 0),
    -- Lo que paga el seguro + lo que paga el paciente = subtotal
    CONSTRAINT ck_factura_cuadre          CHECK (monto_seguro + monto_paciente = subtotal),
    CONSTRAINT ck_factura_saldo           CHECK (saldo >= 0 AND saldo <= monto_paciente),
    CONSTRAINT ck_factura_estado          CHECK (estado IN ('pendiente','pagada','anulada')),
    -- Una factura pagada no puede tener saldo pendiente
    CONSTRAINT ck_factura_pagada_sin_saldo CHECK (estado <> 'pagada' OR saldo = 0)
);

CREATE TABLE clinica.factura_linea (
    id_factura       INTEGER       NOT NULL,
    numero_linea     SMALLINT      NOT NULL,
    concepto         VARCHAR(12)   NOT NULL,
    id_medicamento   INTEGER       NULL,
    cantidad         INTEGER       NOT NULL DEFAULT 1,
    precio_unitario  NUMERIC(10,2) NOT NULL,
    importe          NUMERIC(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,

    CONSTRAINT pk_factura_linea PRIMARY KEY (id_factura, numero_linea),
    CONSTRAINT fk_faclinea_factura FOREIGN KEY (id_factura)
        REFERENCES clinica.factura (id_factura)
        ON DELETE CASCADE,
    CONSTRAINT fk_faclinea_medicamento FOREIGN KEY (id_medicamento)
        REFERENCES clinica.medicamento (id_medicamento)
        ON DELETE RESTRICT,
    CONSTRAINT ck_faclinea_numero   CHECK (numero_linea > 0),
    CONSTRAINT ck_faclinea_concepto CHECK (concepto IN ('consulta','medicamento')),
    CONSTRAINT ck_faclinea_concepto_medicamento
        CHECK ((concepto = 'medicamento') = (id_medicamento IS NOT NULL)),
    CONSTRAINT ck_faclinea_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_faclinea_precio   CHECK (precio_unitario >= 0)
);

CREATE UNIQUE INDEX uq_factura_linea_consulta
    ON clinica.factura_linea (id_factura)
    WHERE concepto = 'consulta';

CREATE TABLE clinica.pago (
    id_pago           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_factura        INTEGER       NOT NULL,
    fecha             TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    monto             NUMERIC(12,2) NOT NULL,
    metodo            VARCHAR(15)   NOT NULL,
    referencia        VARCHAR(40)   NULL,
    id_recepcionista  INTEGER       NULL,

    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_factura FOREIGN KEY (id_factura)
        REFERENCES clinica.factura (id_factura)
        ON DELETE RESTRICT,
    CONSTRAINT fk_pago_recepcionista FOREIGN KEY (id_recepcionista)
        REFERENCES clinica.recepcionista (id_persona)
        ON DELETE SET NULL,
    CONSTRAINT ck_pago_monto  CHECK (monto > 0),
    CONSTRAINT ck_pago_metodo CHECK (metodo IN ('efectivo','tarjeta','transferencia')),
    CONSTRAINT ck_pago_referencia CHECK (metodo = 'efectivo' OR referencia IS NOT NULL)
);
